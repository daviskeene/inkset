const ComparePage = () => {
  const { themeKey } = useThemeKey();
  const inksetPlugins = React.useMemo(
    () => [
      INKSET_CODE_BY_THEME[themeKey] ?? INKSET_CODE_BY_THEME.dark,
      INKSET_MATH,
      INKSET_TABLE,
      INKSET_DIAGRAM_BY_THEME[themeKey] ?? INKSET_DIAGRAM_BY_THEME.dark,
    ],
    [themeKey],
  );
  const streamdownPlugins = React.useMemo(
    () => ({
      code: STREAMDOWN_CODE_BY_THEME[themeKey] ?? STREAMDOWN_CODE_BY_THEME.dark,
      math: streamdownMath,
      mermaid: streamdownMermaid,
    }),
    [themeKey],
  );
  const shikiThemePair: [ThemeInput, ThemeInput] = [
    ...(SHIKI_THEME_PAIR_BY_KEY[themeKey] ?? SHIKI_THEME_PAIR_BY_KEY.dark),
  ];
  const [scenarioKey, setScenarioKey] = useState<string>("rich");
  const [streaming, setStreaming] = useState(false);
  const [streamedContent, setStreamedContent] = useState("");
  const [sharedWidth, setSharedWidth] = useState(480);
  // Track a mobile breakpoint so we can clamp the width slider and tighten
  // chrome. The columns stack under 900px (see GlobalStyles); we treat
  // <768px as "phone" for control-layout purposes.
  const [isNarrow, setIsNarrow] = useState(false);
  useLayoutEffect(() => {
    const mq = window.matchMedia("(max-width: 768px)");
    const update = () => setIsNarrow(mq.matches);
    update();
    mq.addEventListener("change", update);
    return () => mq.removeEventListener("change", update);
  }, []);
  // On mobile the slider's 780px cap would overflow the viewport and waste
  // the right half of the track. Cap the usable range to the actual column
  // width minus gutters, and snap stored state so we never render wider
  // than the device can show.
  const effectiveMaxWidth = isNarrow
    ? Math.max(280, Math.min(780, typeof window !== "undefined" ? window.innerWidth - 32 : 780))
    : 780;
  const effectiveWidth = Math.min(sharedWidth, effectiveMaxWidth);
  // The one column that shows when the columns stack.
  const [stackedColumn, setStackedColumn] = useState<ColumnKey>("inkset");

  const activeScenario = SCENARIOS.find((s) => s.key === scenarioKey) ?? SCENARIOS[0];
  const content =
    streaming || streamedContent.length > 0 ? streamedContent : activeScenario.markdown;

  // Reset the streamed buffer when the scenario changes.
  useEffect(() => {
    setStreamedContent("");
    setStreaming(false);
  }, [scenarioKey]);

  // Single scheduler for all three columns so the rendering is lockstep.
  // Emits ~12 chars per 35ms tick — roughly 340 chars/sec, close to real
  // LLM output speed.
  useEffect(() => {
    if (!streaming) return;
    const target = activeScenario.markdown;
    let index = 0;
    setStreamedContent("");
    const id = window.setInterval(() => {
      index = Math.min(index + 12, target.length);
      setStreamedContent(target.slice(0, index));
      if (index >= target.length) {
        window.clearInterval(id);
        setStreaming(false);
      }
    }, 35);
    return () => window.clearInterval(id);
  }, [streaming, activeScenario]);

  const onStartStream = useCallback(() => {
    setStreamedContent("");
    setStreaming(true);
  }, []);

  const onStopStream = useCallback(() => {
    setStreaming(false);
  }, []);

  const onReset = useCallback(() => {
    setStreamedContent("");
    setStreaming(false);
  }, []);

  return (
    <div
      style={{
        display: "flex",
        flexDirection: "column",
        minHeight: "100vh",
        background: "var(--pg-bg)",
        color: "var(--pg-text-primary)",
        fontFamily: "var(--font-sans), system-ui, -apple-system, sans-serif",
      }}
    >
      <SiteNav activePage="compare" />

      <div className="pg-compare-stage">
        {/* Controls */}
        <div
          className="pg-compare-controls"
          style={{
            padding: "10px 22px",
            borderBottom: "1px solid var(--pg-border-subtle)",
            display: "flex",
            flexWrap: "wrap",
            gap: 14,
            alignItems: "center",
            fontSize: 12,
            background: "var(--pg-bg)",
            flexShrink: 0,
          }}
        >
          <div style={CHIP_GROUP_STYLE}>
            <span style={CHIP_SECTION_LABEL_STYLE}>Scenario</span>
            {SCENARIOS.map((s) => (
              <Chip
                key={s.key}
                label={s.label}
                active={scenarioKey === s.key}
                onClick={() => setScenarioKey(s.key)}
              />
            ))}
          </div>

          <div
            className="pg-compare-divider"
            style={{ width: 1, height: 16, background: "var(--pg-divider)" }}
          />

          <div className="pg-compare-width" style={{ ...CHIP_GROUP_STYLE, gap: 10 }}>
            <span style={CHIP_SECTION_LABEL_STYLE}>Width</span>
            <input
              type="range"
              min={280}
              max={effectiveMaxWidth}
              step={1}
              value={effectiveWidth}
              onChange={(e) => setSharedWidth(Math.round(Number(e.target.value)))}
              style={{ width: 160, maxWidth: "100%", accentColor: "var(--pg-accent)" }}
            />
            <span
              style={{
                fontFamily: "ui-monospace, SFMono-Regular, Menlo, monospace",
                color: "var(--pg-text-muted)",
                fontSize: 11,
                minWidth: 46,
                fontVariantNumeric: "tabular-nums",
              }}
            >
              {effectiveWidth}px
            </span>
          </div>

          <div
            className="pg-compare-divider"
            style={{ width: 1, height: 16, background: "var(--pg-divider)" }}
          />

          <div style={CHIP_GROUP_STYLE}>
            <Chip
              label={streaming ? "Stop stream" : "Start stream"}
              active={streaming}
              variant="accent"
              onClick={streaming ? onStopStream : onStartStream}
              leadingDot
            />
            <Chip label="Reset" variant="quiet" onClick={onReset} />
          </div>
        </div>

        {/* When the columns stack, this switch shows one renderer at a time.
            Otherwise the switching section sits under three copies of the
            same document. */}
        <div className="pg-compare-picker" role="group" aria-label="Renderer">
          {COLUMN_KEYS.map((key) => (
            <button
              key={key}
              type="button"
              aria-pressed={stackedColumn === key}
              onClick={() => setStackedColumn(key)}
            >
              {COLUMN_INFO[key].label}
            </button>
          ))}
        </div>

        {/* Three columns */}
        <div
          className="pg-compare-columns"
          style={{
            display: "flex",
            flex: 1,
            minHeight: 0,
            overflow: "hidden",
          }}
        >
          <Column
            label={COLUMN_INFO.inkset.label}
            hiddenWhenStacked={stackedColumn !== "inkset"}
            upFrontKb={BUNDLE_SIZES.inkset.upFrontKb}
            packages={COLUMN_INFO.inkset.packages}
            note={COLUMN_INFO.inkset.note}
            accent
          >
            {/* No `width` prop: Inkset measures this wrapper, which shrinks with
              the column like the other two renderers' wrappers do. */}
            <div style={{ width: effectiveWidth, maxWidth: "100%" }}>
              <Inkset
                content={content}
                streaming={streaming}
                plugins={inksetPlugins}
                theme={INKSET_THEME}
                font={sans.style.fontFamily}
                fontSize={14}
                lineHeight={21}
                blockSpacing={INKSET_BLOCK_SPACING}
                headingSizes={[1.5, 1.25, 1.1, 1]}
                headingWeights={[700, 700, 600, 600]}
                headingLineHeights={[1.2, 1.22, 1.25, 1.3]}
                headingTracking={[-0.02, -0.01, 0, 0]}
              />
            </div>
          </Column>

          <Column
            label={COLUMN_INFO.reactMarkdown.label}
            hiddenWhenStacked={stackedColumn !== "reactMarkdown"}
            upFrontKb={BUNDLE_SIZES["react-markdown"].upFrontKb}
            packages={COLUMN_INFO.reactMarkdown.packages}
            note={COLUMN_INFO.reactMarkdown.note}
          >
            <div style={{ width: effectiveWidth, maxWidth: "100%" }}>
              <div className="rm-prose">
                <ReactMarkdown
                  remarkPlugins={[remarkGfm, remarkMath]}
                  rehypePlugins={[rehypeKatex, rehypeHighlight]}
                >
                  {content}
                </ReactMarkdown>
              </div>
            </div>
          </Column>

          <Column
            label={COLUMN_INFO.streamdown.label}
            hiddenWhenStacked={stackedColumn !== "streamdown"}
            upFrontKb={BUNDLE_SIZES.streamdown.upFrontKb}
            packages={COLUMN_INFO.streamdown.packages}
            note={COLUMN_INFO.streamdown.note}
          >
            <div className="sd-column" style={{ width: effectiveWidth, maxWidth: "100%" }}>
              <Streamdown
                plugins={streamdownPlugins}
                mode={streaming ? "streaming" : "static"}
                shikiTheme={shikiThemePair}
                controls={false}
                animated={false}
              >
                {content}
              </Streamdown>
            </div>
          </Column>
        </div>
      </div>

      <SwitchSection />

      <Footer />

      <GlobalStyles />
    </div>
  );
};

