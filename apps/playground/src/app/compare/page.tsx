const DiffBlock = ({ title, diff }: { title: string; diff: string }) => {
  return (
    <figure className="pg-compare-diff">
      <figcaption>{title}</figcaption>
      <pre>
        <code>
          {diff.split("\n").map((line, index) => (
            <span
              key={index}
              data-change={
                line.startsWith("+") ? "add" : line.startsWith("-") ? "remove" : undefined
              }
            >
              {line || " "}
            </span>
          ))}
        </code>
      </pre>
    </figure>
  );
};

const AgentPrompt = () => {
  const [copied, setCopied] = useState(false);
  useEffect(() => {
    if (!copied) return;
    const id = window.setTimeout(() => setCopied(false), 1600);
    return () => window.clearTimeout(id);
  }, [copied]);

  return (
    <div className="pg-compare-switch-prompt">
      <code>{AGENT_PROMPT}</code>
      <button
        type="button"
        onClick={() => {
          void navigator.clipboard?.writeText(AGENT_PROMPT).then(() => setCopied(true));
        }}
      >
        {copied ? "Copied" : "Copy"}
      </button>
    </div>
  );
};

